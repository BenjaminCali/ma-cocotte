        </p>

        <ol class="preparation-etapes">
            <li class="preparation-etape">Couper le bœuf en gros cubes. Éplucher les carottes et les couper en rondelles. Émincer l’oignon et hacher l’ail.</li>
            <li class="preparation-etape">Faire revenir les lardons avec l’huile dans la cocotte, puis les réserver dans une assiette.</li>
            <li class="preparation-etape">Faire dorer les morceaux de bœuf en plusieurs fois. Ajouter l’oignon et les carottes, puis faire revenir pendant 5 minutes.</li>
            <li class="preparation-etape">Ajouter l’ail et la farine. Mélanger pendant 1 minute.</li>
            <li class="preparation-etape">Verser le vin et le bouillon. Ajouter les lardons et le bouquet garni. Saler légèrement et poivrer.</li>
            <li class="preparation-etape">Couvrir et laisser mijoter à feu doux pendant 2 h 30. Remuer de temps en temps et ajouter un peu d’eau si nécessaire.</li>
            <li class="preparation-etape">Couper les champignons en quartiers, les faire revenir dans la poêle et les ajouter dans la cocotte.</li>
            <li class="preparation-etape">Poursuivre la cuisson pendant environ 30 minutes, jusqu’à ce que la viande soit tendre. Retirer le bouquet garni avant de servir.</li>

    <section class="preparation">
        <h2 class="section-titre">Préparation</h2>
        <p class="preparation-temps">
            <strong>Temps total :</strong> environ 2h10 (Préparation : 25 min | Cuisson : environ 1h45)
        </p>

        <ol class="preparation-etapes">
            <li class="preparation-etape">Couper le veau en gros morceaux. Éplucher les carottes et les couper en rondelles. Éplucher l’oignon et le piquer avec les clous de girofle.</li>
            <li class="preparation-etape">Mettre la viande dans la cocotte et la couvrir d’eau froide. Porter à frémissement et retirer l’écume.</li>
            <li class="preparation-etape">Ajouter les carottes, l’oignon et le bouquet garni. Saler légèrement et poivrer. Couvrir et laisser mijoter doucement pendant environ 1 h 30, jusqu’à ce que la viande soit tendre. Si utilisés, ajouter les oignons grelots épluchés pour les 30 dernières minutes.</li>
            <li class="preparation-etape">Couper les champignons en quartiers. Les faire revenir dans une poêle avec 10 g de beurre pendant 8 à 10 minutes.</li>
            <li class="preparation-etape">Égoutter la viande et les légumes en conservant le bouillon dans le saladier. Retirer l’oignon piqué et le bouquet garni.</li>
            <li class="preparation-etape">Dans une casserole, faire fondre les 30 g de beurre restants. Ajouter la farine et mélanger pendant 2 minutes sans laisser colorer.</li>
            <li class="preparation-etape">Verser progressivement 60 cl de bouillon chaud en fouettant. Laisser épaissir pendant 5 à 10 minutes.</li>
            <li class="preparation-etape">Ajouter la crème et le jus de citron. Réunir la sauce, la viande, les légumes et les champignons dans la cocotte. Réchauffer doucement pendant 5 minutes et rectifier l’assaisonnement.</li>
            <li class="preparation-etape">Cuire le riz selon les indications du paquet et le servir avec la blanquette.</li>
        </ol>


    <section class="preparation">
        <h2 class="section-titre">Préparation</h2>

        <p class="preparation-temps">
            <strong>Temps total :</strong> environ 3h55 (Préparation : 25 min | Cuisson : environ 3h30)
        </p>

        <ol class="preparation-etapes">
            <li class="preparation-etape">Déposer la viande dans la marmite et la couvrir d’eau froide. Porter doucement à frémissement, puis retirer l’écume avec l’écumoire.</li>
            <li class="preparation-etape">Éplucher l’oignon et le piquer avec les clous de girofle. L’ajouter avec le céleri nettoyé, le bouquet garni, le poivre et un peu de gros sel.</li>
            <li class="preparation-etape">Laisser mijoter pendant 2 h 30 avec le couvercle légèrement entrouvert. Ajouter de l’eau chaude si nécessaire pour garder la viande immergée.</li>
            <li class="preparation-etape">Éplucher les carottes et les navets. Nettoyer soigneusement les poireaux, puis couper les légumes en gros morceaux.</li>
            <li class="preparation-etape">Ajouter ces légumes dans la marmite et poursuivre la cuisson pendant 1 heure. Ajouter les os à moelle pour les 30 dernières minutes, si souhaité.</li>
            <li class="preparation-etape">Pendant ce temps, éplucher les pommes de terre. Les cuire séparément dans une casserole d’eau salée pendant 20 à 25 minutes, puis les égoutter.</li>
            <li class="preparation-etape">Vérifier que la viande est fondante. Retirer le bouquet garni et servir avec les légumes, les pommes de terre et un peu de bouillon.</li>
        </ol>


